from dataclasses import dataclass, field, replace
from functools import partial
from pathlib import Path
from typing import Any

import structlog
import yaml
from sqlalchemy.orm import Session

from app.config import get_settings
from app.domain.generation import (
    Batch,
    Outcome,
    bank_item,
    brief,
    parse_request,
    settle,
    slugify,
    words_for,
)
from app.llm import get_item_writer
from app.llm.writer import MAX_OUTPUT_TOKENS, ItemWriter
from app.services.budget import price_book
from app.services.metering import run_metered

log = structlog.get_logger()
FEATURE = "content_gen"
PROMPT_TOKENS = 1_500
ACCEPTED = ("ok", "fixed")


class _Dumper(yaml.SafeDumper):
    """Writes multi-line text (dialogues, emails) as readable blocks, for review in the drafts."""


_Dumper.add_representer(
    str,
    lambda dumper, text: dumper.represent_scalar(
        "tag:yaml.org,2002:str", text, style="|" if "\n" in text else None
    ),
)


@dataclass
class GenerationReport:
    written: list[str] = field(default_factory=list)
    cached: int = 0
    counts: dict[str, int] = field(
        default_factory=lambda: dict.fromkeys(("ok", "fixed", "rejected"), 0)
    )


def generate(
    session: Session, user_id: int, request: Path, writer: ItemWriter | None = None
) -> GenerationReport:
    """Content pipeline step: each batch is written, checked and reviewed once, into a draft.

    Drafts are never live; `promote` copies their accepted items into the item bank.
    """
    writer = writer or get_item_writer()
    content_dir = get_settings().content_dir
    tasks = yaml.safe_load((content_dir / "exam_tasks.yaml").read_text())
    batches = parse_request(yaml.safe_load(request.read_text()))
    drafts_dir = content_dir / "drafts" / request.stem
    taken = _bank_slugs(content_dir) | _draft_slugs(drafts_dir)
    report = GenerationReport()
    for batch in batches:
        text = brief(tasks, batch)
        key = batch.key(text, writer.fingerprint, writer.model)
        path = drafts_dir / f"{batch.cefr.lower()}-{key[:12]}.yaml"
        if path.exists():
            report.cached += 1
            continue
        outcomes = _run_batch(session, user_id, writer, batch, tasks=tasks, text=text, taken=taken)
        _write_draft(path, batch, outcomes, request=request.stem, model=writer.model, key=key)
        session.commit()
        report.written.append(str(path.relative_to(content_dir)))
        for outcome in outcomes:
            report.counts[outcome.status] += 1
        log.info("content_batch_written", path=path.name, statuses=[o.status for o in outcomes])
    return report


def promote(request: Path) -> int:
    """Rebuilds the request's item bank from its drafts; edit the drafts, never the bank."""
    content_dir = get_settings().content_dir
    target = content_dir / "items" / f"{request.stem}.yaml"
    if target.exists() and yaml.safe_load(target.read_text()).get("generated_from") != request.stem:
        raise ValueError(f"{target.name} was written by hand; choose another request name")
    drafts = [
        yaml.safe_load(p.read_text())
        for p in sorted((content_dir / "drafts" / request.stem).glob("*.yaml"))
    ]
    if not drafts:
        raise ValueError(f"No drafts for {request.stem}; run `make generate` first")
    items = [e["item"] for d in drafts for e in d["items"] if e["status"] in ACCEPTED]
    bank = {"skill": drafts[0]["skill"], "generated_from": request.stem, "items": items}
    header = (
        f"# Generated by `make generate` from content/generation/{request.stem}.yaml and not\n"
        f"# yet reviewed by a person. Edit content/drafts/{request.stem}/ and run `make promote`.\n"
    )
    target.write_text(header + _dump(bank))
    return len(items)


def _run_batch(
    session: Session,
    user_id: int,
    writer: ItemWriter,
    batch: Batch,
    *,
    tasks: dict[str, Any],
    text: str,
    taken: set[str],
) -> list[Outcome]:
    pricing = price_book().for_model(writer.model)
    words = words_for(tasks, batch)
    options = int(tasks[batch.skill]["format"]["options"])
    avoid = sorted(taken)
    drafts = run_metered(
        session,
        user_id=user_id,
        feature=FEATURE,
        model=writer.model,
        estimate_usd=pricing.cost(
            {
                "input_tokens": PROMPT_TOKENS + len(text) / 3 + 10 * len(avoid),
                "output_tokens": MAX_OUTPUT_TOKENS,
            }
        ),
        call=partial(writer.write, text, batch.count, avoid),
    )
    drafts = [replace(d, slug=slugify(batch.skill, batch.cefr, d.slug, taken)) for d in drafts]
    shown = sum(len(d.document) + len(d.explanation) + sum(map(len, d.options)) for d in drafts)
    verdicts = run_metered(
        session,
        user_id=user_id,
        feature=FEATURE,
        model=writer.model,
        estimate_usd=pricing.cost(
            {
                "input_tokens": PROMPT_TOKENS + (len(text) + shown) / 3,
                "output_tokens": MAX_OUTPUT_TOKENS,
            }
        ),
        call=partial(writer.review, text, drafts),
    )
    return [settle(d, v, words, options) for d, v in zip(drafts, verdicts, strict=True)]


def _write_draft(
    path: Path, batch: Batch, outcomes: list[Outcome], *, request: str, model: str, key: str
) -> None:
    draft = {
        "request": request,
        "skill": batch.skill,
        "cefr": batch.cefr,
        "themes": list(batch.themes),
        "format": batch.format,
        "model": model,
        "key": key,
        "items": [
            {
                "status": o.status,
                "issues": o.issues,
                "item": bank_item(batch, o.draft),
            }
            for o in outcomes
        ],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_dump(draft))


def _bank_slugs(content_dir: Path) -> set[str]:
    return {
        item["slug"]
        for bank in (content_dir / "items").glob("*.yaml")
        for item in yaml.safe_load(bank.read_text())["items"]
    }


def _draft_slugs(drafts_dir: Path) -> set[str]:
    return {
        entry["item"]["slug"]
        for path in drafts_dir.glob("*.yaml")
        for entry in yaml.safe_load(path.read_text())["items"]
    }


def _dump(data: dict[str, Any]) -> str:
    return yaml.dump(data, Dumper=_Dumper, allow_unicode=True, sort_keys=False, width=100)
